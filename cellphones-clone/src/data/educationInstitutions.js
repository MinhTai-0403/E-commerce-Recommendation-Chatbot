const HCMC_EDUCATION_DIRECTORY_URL = '/data/hcmc-education-institutions.json';
let hcmcEducationDirectoryPromise;

function normalizeText(value = '') {
  return String(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/đ/g, 'd')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

export function getEmailDomain(email = '') {
  return String(email).trim().toLowerCase().split('@')[1] || '';
}

export function findInstitutionByEmail(email = '') {
  const domain = getEmailDomain(email);
  if (!domain) return null;

  return EDUCATION_INSTITUTIONS.find((institution) =>
    institution.domains.some((knownDomain) =>
      domain === knownDomain || domain.endsWith(`.${knownDomain}`)
    )
  ) || null;
}

export function findInstitutionByName(value = '', directory = []) {
  const normalized = normalizeText(value);
  if (!normalized) return null;

  return [...EDUCATION_INSTITUTIONS, ...directory].find((institution) => {
    const names = [
      institution.name,
      institution.sourceName,
      institution.shortName,
      ...(institution.domains || []),
    ];
    return names.some((name) => normalizeText(name) === normalized);
  }) || null;
}

export async function loadHcmcEducationInstitutions() {
  if (!hcmcEducationDirectoryPromise) {
    hcmcEducationDirectoryPromise = fetch(HCMC_EDUCATION_DIRECTORY_URL, {
      cache: 'force-cache',
    })
      .then((response) => {
        if (!response.ok) {
          throw new Error(`Không thể tải danh sách trường TP.HCM (${response.status}).`);
        }
        return response.json();
      })
      .then((payload) => Array.isArray(payload) ? payload : payload.institutions || [])
      .catch((error) => {
        hcmcEducationDirectoryPromise = undefined;
        throw error;
      });
  }

  return hcmcEducationDirectoryPromise;
}

function scoreInstitution(institution, normalizedQuery) {
  const values = [
    institution.name,
    institution.sourceName,
    institution.shortName,
    institution.level,
    institution.wardName,
    ...(institution.domains || []),
  ]
    .filter(Boolean)
    .map(normalizeText);

  if (values.some((value) => value === normalizedQuery)) return 0;
  if (values.some((value) => value.startsWith(normalizedQuery))) return 1;
  if (values.some((value) => value.split(' ').some((word) => word.startsWith(normalizedQuery)))) return 2;
  if (values.some((value) => value.includes(normalizedQuery))) return 3;
  return Number.POSITIVE_INFINITY;
}

export function searchEducationInstitutions(directory = [], query = '', limit = 40) {
  const normalizedQuery = normalizeText(query);
  const seen = new Set();
  const institutions = [...EDUCATION_INSTITUTIONS, ...directory].filter((institution) => {
    const key = institution.id || normalizeText(institution.name);
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  if (!normalizedQuery) return institutions.slice(0, limit);

  return institutions
    .map((institution) => ({
      institution,
      score: scoreInstitution(institution, normalizedQuery),
    }))
    .filter((result) => Number.isFinite(result.score))
    .sort((left, right) => (
      left.score - right.score
      || left.institution.name.localeCompare(right.institution.name, 'vi')
    ))
    .slice(0, limit)
    .map((result) => result.institution);
}

export function getInstitutionMeta(institution) {
  if (!institution) return '';
  return [
    institution.shortName,
    institution.wardName,
    institution.schoolType,
    institution.domains?.[0],
  ].filter(Boolean).join(' · ');
}
